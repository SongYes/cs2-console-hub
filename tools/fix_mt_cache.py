def dedupe(text: str) -> str:
    """清除循环重复词。

    典型成因：术语替换叠加（"print" 与 "output" 都译成「输出」→「打印输出输出」），
    或离线模型退化（"Bot Bot Bot"）。
    """
    t = text or ""
    # 1) 机器人 / Bot 连续堆叠 -> 单个「机器人 Bot」
    t = re.sub(r"(?:机器人\s*)+Bot", "机器人 Bot", t)
    t = re.sub(r"(?:机器人\s*)+", "机器人 ", t)
    t = re.sub(r"\bBot(?:\s+Bot)+\b", "Bot", t)
    t = re.sub(r"机器人\s+Bot(?:\s+Bot)+", "机器人 Bot", t)
    # 3) 术语替换造成的叠加
    t = re.sub(r"打印输出输出", "打印输出", t)
    t = t.replace("客户端端", "客户端")
    t = t.replace("炸弹网站", "炸弹安放点")
    t = t.replace("歇斯底里", "滞后值")
    t = t.replace("语动词", "混响")
    t = t.replace("评注模式", "解说模式")
    t = t.replace("绩效报告", "性能报告")
    t = t.replace("配置器", "分析器")
    t = t.replace("刻度率", "tick 速率")
    t = t.replace("面部岛", "面岛")
    t = t.replace("现场轨迹", "字段轨迹")
    t = t.replace("生命射击", "急救针")
    t = t.replace("死亡对战", "死斗模式")
    t = re.sub(r"下蹲量", "压低背景音量的幅度", t)
    t = re.sub(r"合作社高的", "合作模式的", t)
    t = re.sub(r"此卷曲的值", "该回合", t)
    t = re.sub(r"蜱虫", "tick", t)
    # 2) 紧邻重复的中文词组（2-6 字）与英文单词
    for _ in range(6):
        before = t
        t = re.sub(r"([\u4e00-\u9fff]{2,6})\1+", r"\1", t)
        t = re.sub(r"\b([A-Za-z][A-Za-z0-9_]{1,15})\b(?:\s+\1\b)+", r"\1", t, flags=re.I)
        t = re.sub(r"([^\s，。、；：！？（）()]{1,6}?)\s+\1(?=[\s，。、；：！？（）()]|$)", r"\1", t)
        if t == before:
            break
    # 3) 重复标点
    t = re.sub(r"([，。、；：！？])\1+", r"\1", t)
    t = re.sub(r"（\s*（", "（", t)
    t = re.sub(r"）\s*）", "）", t)
    t = re.sub(r"\s{2,}", " ", t)
    # 「机器人 Bot」后面若直接接中文，补一个空格（"Bot可能" -> "Bot 可能"）
    t = re.sub(r"机器人 Bot(?=[\u4e00-\u9fff])", "机器人 Bot ", t)
    return t.strip()


def stash_numbers(t, keep, stash):
    """保护小数、版本号、文件名，避免后面的「. -> 。」把它们改坏。

    只有「数字.数字」才算小数（`1."经典"` 这种不是，必须照常转成句号）。
    """
    t = re.sub(r"(?<=\d)\.(?=\d)", stash, t)
    t = re.sub(r"\b[A-Za-z_][A-Za-z0-9_]*\.(?:cfg|txt|dem|dll|exe|json)\b", stash, t)
    return t


def polish(text: str) -> str:
    """轻度规整：只处理空白、标点、重复，不改写用词。

    用于大模型产出的译文（用词本来就正确，过度替换反而会破坏它）。
    """
    t = text or ""
    keep = []

    def stash(m):
        keep.append(m.group(0))
        return f"\x00{len(keep) - 1}\x00"

    t = stash_numbers(t, keep, stash)
    t = re.sub(r"(.)\1{4,}", r"\1\1", t)
    t = re.sub(r"\s{2,}", " ", t)
    if re.search(r"[\u4e00-\u9fff]", t):
        t = t.replace(".", "。")
    t = re.sub(r"\s+([。，、；：！？）])", r"\1", t)
    t = re.sub(r"([。，、；：])\1+", r"\1", t)
    t = re.sub(r"。{2,}", "。", t)
    # 半角标点统一为全角（仅在中文语境里）
    t = t.replace(", ", "，").replace("; ", "；").replace(": ", "：")
    t = t.strip()
    if re.search(r"[\u4e00-\u9fff]", t) and not t.endswith(("。", "！", "？", "）", ")", "：", "，", "；", "…")):
        t += "。"
    t = re.sub(r"\x00(\d+)\x00", lambda m: keep[int(m.group(1))], t)
    return dedupe(t)


def postprocess(text: str) -> str:
    """完整纠错：术语对照表 + 正则修正。用于机器翻译/离线模型的产出。"""
    t = text or ""
    # 先把版本号/小数/文件名等保护起来，避免把小数点当句号替换
    keep = []

    def stash(m):
        keep.append(m.group(0))
        return f"\x00{len(keep) - 1}\x00"

    t = stash_numbers(t, keep, stash)

    for rx, rep in COMPILED_A:
        t = rx.sub(rep, t)
    for rx, rep in COMPILED_C:
        t = rx.sub(rep, t)
    # B. 正则类修正
    t = re.sub(r"(.)\1{4,}", r"\1\1", t)                 # 重复字符循环
    t = re.sub(r"（\s*请检查[^）]*）", "", t)              # 离线模型偶尔吐出的自检提示
    t = re.sub(r"\(\s*请检查[^)]*\)", "", t)
    t = re.sub(r"\s{2,}", " ", t)
    if re.search(r"[\u4e00-\u9fff]", t):
        t = t.replace(".", "。")
    t = re.sub(r"\s+([。，、；：！？）])", r"\1", t)
    t = re.sub(r"([。，、；：])\1+", r"\1", t)
    t = re.sub(r"。{2,}", "。", t)
    t = t.strip()
    if re.search(r"[\u4e00-\u9fff]", t) and not t.endswith(("。", "！", "？", "）", ")", "：", "，", "；", "…")):
        t += "。"
    # 还原保护片段
    t = re.sub(r"\x00(\d+)\x00", lambda m: keep[int(m.group(1))], t)
    return dedupe(t)


# 译文质量较好的引擎：只用轻度规整，不做术语替换
GOOD_ENGINES = {"deepseek", "openai", "gpt", "claude"}


def fix_for(engine: str, text: str) -> str:
    out = polish(text) if engine in GOOD_ENGINES else postprocess(text)
    return dedupe(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--cache", default=str(CACHE))
    args = ap.parse_args()
    path = Path(args.cache)
    data = json.loads(path.read_text(encoding="utf-8"))
    changed = []
    by_src = {}
    for k, v in data.items():
        if not isinstance(v, dict) or not v.get("zh"):
            continue
        src = v.get("src", "mt")
        new = fix_for(src, v["zh"])
        if new != v["zh"]:
            changed.append((k, v["zh"], new, src))
            by_src[src] = by_src.get(src, 0) + 1
            if not args.dry_run:
                v["zh"] = new
                v["fixed"] = True
    if not args.dry_run:
        path.write_text(json.dumps(data, ensure_ascii=False, indent=0), encoding="utf-8")
    print(f"[{'预览' if args.dry_run else '已修正'}] 命中 {len(changed)} / {len(data)} 条；"
          f"按引擎 {by_src}")
    for k, old, new, src in changed[:10]:
        print(f"  [{src}] 原文: {k[:64]}")
        print(f"        旧译: {old[:88]}")
        print(f"        新译: {new[:88]}")
        print()


if __name__ == "__main__":
    main()
